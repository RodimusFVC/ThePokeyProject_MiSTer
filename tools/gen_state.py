#!/usr/bin/env python3
"""One field table -> both sides of the state contract (plan section 1).

Generates
  verilator/pokey_dbg_pos.svh: field LSB localparams (rig adapters)
  rtl/pokey_cx_dbg.svh       : `assign dbg_state = {...}` from the RTL signal names
                               (only used under `ifdef POKEY_DBG)
  verilator/pokey_state.h    : field enum, names, widths, LSB offsets, groups
                               (C++ side: comparator + ref mapping)

Field order = MSB first in dbg_state.  Each row: (name, width, group, rtl_expr).
Groups let a milestone restrict the comparison (plan M5).
"""
import os
import sys

P = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

FIELDS = []
for c in range(1, 5):
    FIELDS += [
        (f"ch{c}_audf", 8, "reg", f"audf[{c-1}]"),
        (f"ch{c}_audc", 8, "reg", f"audc[{c-1}]"),
        (f"ch{c}_counter", 8, "chan", f"cnt[{c-1}]"),
        (f"ch{c}_borrow_cnt", 3, "chan", f"bcnt[{c-1}]"),
        (f"ch{c}_output", 1, "chan", f"outp[{c-1}]"),
        (f"ch{c}_filter_sample", 1, "chan", f"fsmp[{c-1}]"),
    ]
FIELDS += [
    ("audctl", 8, "reg", "audctl"),
    ("skctl", 8, "reg", "skctl"),
    ("irqen", 8, "reg", "irqen"),
    ("irqst", 8, "irq", "irqst"),
    ("skstat", 8, "irq", "skstat"),
    ("allpot", 8, "pot", "allpot"),
    ("clk28", 5, "prescale", "clk28"),
    ("clk114", 7, "prescale", "clk114"),
    ("p4", 4, "poly", "p4"),
    ("p5", 5, "poly", "p5"),
    ("p9", 9, "poly", "p9"),
    ("p17", 17, "poly", "p17"),
    ("pot_counter", 8, "pot", "pot_cnt"),
]
FIELDS += [(f"pot{i}", 8, "pot", f"potx[{i}]") for i in range(8)]
FIELDS += [
    ("serin", 8, "serial", "serin"),
    ("serout", 8, "serial", "serout"),
    ("serin_shift", 10, "serial", "serin_shift"),
    ("serout_shift", 10, "serial", "serout_shift"),
    ("serout_full", 1, "serial", "serout_full"),
    ("ser_iclk", 1, "serial", "ser_iclk"),
    ("ser_oclk", 1, "serial", "ser_oclk"),
    ("sod_twotone", 1, "serial", "sod_twotone"),
    ("out_raw", 16, "out", "out_raw"),
    ("irq", 1, "irq", "irq_lvl"),
    ("sod", 1, "serial", "sod_lvl"),
    ("oclk", 1, "serial", "oclk_lvl"),
]
GROUPS = ["reg", "chan", "irq", "serial", "pot", "prescale", "poly", "out"]


def main():
    width = sum(f[1] for f in FIELDS)
    # LSB offsets: first field is the MSB end
    lsb = []
    pos = width
    for f in FIELDS:
        pos -= f[1]
        lsb.append(pos)
    assert pos == 0
    hdr = "// GENERATED by tools/gen_state.py -- do not edit\n"

    sv = [hdr, f"// dbg_state width = {width}\n", "assign dbg_state = {\n"]
    for i, f in enumerate(FIELDS):
        sep = "," if i + 1 < len(FIELDS) else ""
        sv.append(f"    {f[3]}{sep}   // {f[0]} [{lsb[i]+f[1]-1}:{lsb[i]}]\n")
    sv.append("};\n")
    with open(os.path.join(P, "rtl", "pokey_cx_dbg.svh"), "w") as fh:
        fh.write("".join(sv))
    pos = [hdr] + [f"localparam integer DBG_LSB_{f[0]} = {lsb[i]};\n" for i, f in enumerate(FIELDS)]
    with open(os.path.join(P, "verilator", "pokey_dbg_pos.svh"), "w") as fh:
        fh.write("".join(pos))

    h = [hdr, "#pragma once\n#include <cstdint>\n\n",
         f"#define POKEY_STATE_WIDTH {width}\n",
         f"#define POKEY_STATE_WORDS {(width + 31) // 32}\n",
         f"#define POKEY_NFIELDS {len(FIELDS)}\n\n"]
    h.append("enum pokey_group {\n")
    for i, g in enumerate(GROUPS):
        h.append(f"    G_{g} = 1u << {i},\n")
    h.append("};\n\n")
    h.append("// X(name, width, lsb, group)\n#define POKEY_STATE_FIELDS \\\n")
    for i, f in enumerate(FIELDS):
        h.append(f"    X({f[0]}, {f[1]}, {lsb[i]}, G_{f[2]}) \\\n")
    h.append("\n")
    h.append("enum pokey_field {\n#define X(n, w, l, g) F_##n,\n    POKEY_STATE_FIELDS\n#undef X\n};\n\n")
    h.append("struct pokey_field_info { const char *name; unsigned width, lsb, group; };\n")
    h.append("static const pokey_field_info POKEY_FIELD_INFO[POKEY_NFIELDS] = {\n"
             "#define X(n, w, l, g) { #n, w, l, g },\n    POKEY_STATE_FIELDS\n#undef X\n};\n\n")
    h.append("struct pokey_state { uint32_t v[POKEY_NFIELDS]; };\n\n")
    h.append("// unpack a flat little-endian word array (Verilator VlWide) into fields\n"
             "static inline void pokey_state_unpack(const uint32_t *w, pokey_state &s) {\n"
             "    for (unsigned i = 0; i < POKEY_NFIELDS; i++) {\n"
             "        unsigned l = POKEY_FIELD_INFO[i].lsb, n = POKEY_FIELD_INFO[i].width;\n"
             "        uint32_t v = 0;\n"
             "        for (unsigned b = 0; b < n; b++) v |= ((w[(l + b) >> 5] >> ((l + b) & 31)) & 1u) << b;\n"
             "        s.v[i] = v;\n"
             "    }\n}\n")
    with open(os.path.join(P, "verilator", "pokey_state.h"), "w") as fh:
        fh.write("".join(h))
    print(f"gen_state: {len(FIELDS)} fields, {width} bits")


if __name__ == "__main__":
    sys.exit(main())
